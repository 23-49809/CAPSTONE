<p>These terms apply when you use SMART ASSESS, the online system of the Municipal Assessor's Office of Mabini, Batangas (the "Office"). You do not need an account to apply. Before starting an application you are asked to accept the Terms and Conditions, which cover the same points as this page. If you do not agree, please do not submit an application; you may ask the Office about other ways to transact.</p>

<h2 id="services">1. The services</h2>
<p><strong>Document requests.</strong> You may request:</p>
<ul>
  <li>Certified True Copy of Tax Declaration (CTC-TD)</li>
  <li>Certification of No/With Existing Improvement</li>
  <li>Certification of Property/No Property Holdings</li>
  <li>Certification of No Liens and Encumbrances</li>
  <li>Certification of Assessment</li>
</ul>
<p><strong>Land transfers.</strong> You may submit land transfer applications by sale, donation or inheritance. Further information and documents may be needed depending on the transfer.</p>
<p>Completed documents are claimed in person at the Office during office hours.</p>

<h2 id="accuracy">2. Accurate information</h2>
<p>You must give true, correct and up-to-date information. False, misleading, incomplete or fraudulent information or documents may cause your request to be delayed or rejected, and may be dealt with under applicable laws and regulations.</p>

<h2 id="documents">3. Document requirements</h2>
<p>Depending on your request, you may need to upload documents such as a valid ID, an authorization letter if you are applying for the property owner, a Certified True Copy of a Tax Declaration or Title, a Notarial Deed of Sale or Donation, a Vicinity Map, a Tax Clearance, or a Certification of No Improvement.</p>
<ul>
  <li>Files must be JPG, PNG, WEBP or PDF, up to 5 MB each.</li>
  <li>Documents must be genuine, complete and clearly readable.</li>
  <li>Only submit documents you are entitled to use.</li>
  <li>The Office may ask for further documents or for originals.</li>
</ul>

<h2 id="processing">4. Request processing</h2>
<p>A new request starts as Pending and becomes Processing when staff begin working on it. It may then be marked Out for Release, Rejected or Timed Out. Authorized personnel review what you submit manually.</p>
<p>Submitting a request does not mean it is approved or completed. Every request remains subject to the Office's requirements, verification, evaluation and approval procedures. A rejected request may include a reason, and the Office may tell you what is needed.</p>

<h2 id="tracking">5. Tracking your request</h2>
<p>You receive a reference number after submitting. Use it on the Track Request page to check your request's status. Anyone with your reference number can see the applicant's name, the service requested and the status, so keep it private.</p>

<h2 id="notifications">6. Notifications</h2>
<p>Status changes appear in request tracking and do not automatically send an SMS or email. Staff may choose to message you about your request by SMS, or by email if you gave an address.</p>
<p>Delivery depends on outside providers and networks and is not guaranteed. Please give a valid, active number and check request tracking regularly rather than relying on a message.</p>

<h2 id="saved">7. Saved applications</h2>
<p>Your application saves automatically while you fill it in, and you may receive a recovery code or resume link to continue on another device. Anyone who has them can open your saved application. Unsubmitted applications expire 7 days after your last change, and no later than 30 days after they were started.</p>

