</ul>

<h2 id="responsibilities">9. Your responsibilities</h2>
<ul>
  <li>Check your application before submitting it.</li>
  <li>Keep your reference number, recovery code and resume link private.</li>
  <li>Have the authority to apply if you act for the property owner.</li>
  <li>Keep your contact details correct, and tell the Office if they change.</li>
  <li>Report suspected unauthorized access to the Office right away.</li>
</ul>

